"""General 与具体协作支持的入口边界，不判断身份或业务权限。"""
import re


def platform_fault_topic(message: str) -> str:
    """仅识别资料覆盖的明确故障；功能方法和单纯权限限制不视为技术异常。"""
    text = (message or '').lower()
    for topic, clues in (
        ('document_sync', ('保存失败', '无法保存', '保存不了', '不能保存', '协同不同步', '内容不同步', '同步延迟', '正在重连', '看不到最新修改')),
        ('file_transfer', ('上传失败', '无法上传', '上传不了', '上传卡住', '上传进度停滞', '下载失败', '无法下载', '下载无响应', '下载没反应', '下载被阻止', '下载中断')),
        ('page_loading', ('白屏', '页面空白', '持续加载', '一直转圈', '加载失败', '按钮无反应', '按钮点击无反应')),
        ('notifications', ('没收到提醒', '未收到提醒', '通知未收到', '提醒不显示', '提醒没收到', '没收到通知', '没有桌面弹窗')),
    ):
        if any(clue in text for clue in clues):
            return topic
    if re.search(r'[@＠].{0,24}(?:没有|没收到|未收到).{0,6}(?:提醒|通知)', text):
        return 'notifications'
    return ''


def is_general_overview(message: str) -> bool:
    text = (message or '').lower().strip()
    if platform_fault_topic(text):
        return False
    # 已有明确操作目标或角色/接口问题，不因“新用户”“介绍”等词退回概述。
    if any(word in text for word in (
        'api', '接口', '/sandbox/', 'scope', '403', 'guest', 'member', 'admin',
        '权限', '看不到', '打不开', '不可见', '无法保存', '上传失败',
        '创建', '新建', '邀请', '分享', '申请', '审批', '批注', '编辑', '配置',
    )):
        return False
    return bool(re.search(
        r'(?:平台|系统|产品|助手|ordo\s*|你)(?:主要)?(?:能|可以)(?:帮我)?(?:做|解决|提供|帮).*?(?:什么|哪些)'
        r'|(?:平台|系统|产品|助手|ordo\s*)(?:主要)?(?:有|支持)(?:什么|哪些).*?(?:功能|用途|能力|问题|服务)?'
        r'|介绍.{0,6}(?:平台|系统|产品|助手|ordo)'
        r'|(?:平台|系统|产品|助手)(?:是|主要是)做什么'
        r'|(?:不知道|不清楚)(?:该|应该)?从哪(?:里|儿)?开始'
        r'|(?:你|助手|ordo\s*)(?:能|可以)帮我什么'
        r'|(?:平台|系统|助手|ordo|你).{0,4}(?:支持范围|整体功能|概述|功能概览)'
        r'|(?:支持范围|整体功能|产品概述).{0,5}(?:什么|哪些)'
        r'|(?:新用户|刚加入团队|第一次使用).{0,12}(?:入门|上手|开始)', text,
    ))
